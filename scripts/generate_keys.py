#!/usr/bin/env python
"""Generate per-tenant API keys and append them to .env (gitignored).

Usage: python scripts/generate_keys.py
Keys are written to .env only - never printed, never written to YAML.
Existing ARBITER_KEY_* entries are left untouched.
"""
import secrets
import sys
from pathlib import Path

import yaml

CONFIG = Path("config/tenants.yaml")
ENV_FILE = Path(".env")

if not CONFIG.exists():
    sys.exit(f"Error: {CONFIG} not found")

tenants = yaml.safe_load(CONFIG.read_text())["tenants"]
existing = ENV_FILE.read_text() if ENV_FILE.exists() else ""
existing_vars = {line.split("=")[0] for line in existing.splitlines() if "=" in line}

to_add = [
    f"ARBITER_KEY_{tid.upper()}=arb_{tid[:8]}_{secrets.token_hex(24)}"
    for tid in tenants
    if f"ARBITER_KEY_{tid.upper()}" not in existing_vars
]
if not to_add:
    print(f"All {len(tenants)} tenant keys already present in .env - nothing changed.")
    sys.exit(0)

with ENV_FILE.open("a") as f:
    if existing and not existing.endswith("\n"):
        f.write("\n")
    f.write("\n# Per-tenant API keys (generated by scripts/generate_keys.py)\n")
    f.write("\n".join(to_add) + "\n")

print(f"Added {len(to_add)} key(s) to .env. Do not commit .env.")
